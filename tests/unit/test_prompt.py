"""Unit tests for generation/prompt.py and run.py prompt handling."""

import torch

from mini_infra.generation import (
    DEFAULT_GOLDEN_MAX_OUTPUT_TOKENS,
    DEFAULT_GOLDEN_PROMPT,
    BatchingMethod,
    FeatureFlag,
    Mode,
    generate,
    get_homogeneous_prompt_lengths,
    get_mixed_output_budgets,
    get_mixed_prompt_lengths,
    get_slots_prompt_lengths,
    make_homogeneous_prompts,
    make_mixed_prompts,
    make_prompt,
    make_sequence,
    make_sequences,
    make_slots_prompts,
)
from mini_infra.testing.smoke_test import build_tiny_model


def test_make_sequence_shape_and_range():
    vocab_size = 32000
    length = 64
    seq = make_sequence(length, vocab_size)

    assert isinstance(seq, torch.Tensor)
    assert seq.shape == (length,)
    assert seq.dtype == torch.long
    assert seq.min().item() >= 1000
    assert seq.max().item() < min(vocab_size, 100000)

    # Small vocab_size case
    small_vocab = 500
    seq_small = make_sequence(16, small_vocab)
    assert seq_small.min().item() >= 1
    assert seq_small.max().item() < small_vocab


def test_make_sequence_determinism_and_salt():
    vocab_size = 151936
    length = 32

    seq1 = make_sequence(length, vocab_size, salt=0)
    seq2 = make_sequence(length, vocab_size, salt=0)
    assert torch.equal(seq1, seq2)

    seq_salted = make_sequence(length, vocab_size, salt=23)
    assert not torch.equal(seq1, seq_salted)


def test_make_sequences_variable_lengths():
    vocab_size = 32000
    lengths = [16, 32, 64, 128]
    seqs = make_sequences(lengths, vocab_size)

    assert isinstance(seqs, list)
    assert len(seqs) == len(lengths)
    for s, expected_len in zip(seqs, lengths):
        assert isinstance(s, torch.Tensor)
        assert s.shape == (expected_len,)

    # Different sequences in batch should have distinct tokens
    assert not torch.equal(seqs[0], seqs[1][:16])


def test_make_prompt_int_compatibility_with_run_py():
    vocab_size = 151936
    length = 128
    batch_size = 3

    # Direct implementation matching run.py's original logic
    generator = torch.Generator(device="cpu").manual_seed(1234 + length)
    low = 1000 if vocab_size > 1000 else 1
    high = min(vocab_size, 100000)
    expected = torch.randint(low, high, (batch_size, length), generator=generator)

    actual = make_prompt(vocab_size, length, batch_size=batch_size)
    assert isinstance(actual, torch.Tensor)
    assert torch.equal(actual, expected)


def test_make_prompt_sequence_lengths():
    vocab_size = 32000
    lengths = [10, 20, 30]
    prompts = make_prompt(vocab_size, lengths)

    assert isinstance(prompts, list)
    assert len(prompts) == 3
    assert [p.shape[0] for p in prompts] == [10, 20, 30]


def test_benchmark_prompt_helpers():
    prompt_length = 128

    # Padding mixed suite helper
    mixed_lens = get_mixed_prompt_lengths(prompt_length)
    assert mixed_lens == [16, 32, 64, 128]

    mixed_prompts = make_mixed_prompts(prompt_length, vocab_size=50000)
    assert len(mixed_prompts) == 4
    assert [p.shape[0] for p in mixed_prompts] == [16, 32, 64, 128]

    # Homogeneous suite helper
    homo_lens = get_homogeneous_prompt_lengths(prompt_length, batch_size=4)
    assert homo_lens == [128, 128, 128, 128]

    homo_prompts = make_homogeneous_prompts(prompt_length, batch_size=2, vocab_size=50000)
    assert len(homo_prompts) == 2
    assert homo_prompts[0].shape == (128,)
    assert homo_prompts[1].shape == (128,)

    # Slots suite helper
    slots_lens = get_slots_prompt_lengths(prompt_length, num_budgets=4)
    assert slots_lens == [128, 128, 128, 128]

    mixed_budgets = get_mixed_output_budgets(64)
    assert mixed_budgets == [8, 16, 32, 64]

    slots_prompts = make_slots_prompts(prompt_length, vocab_size=50000, budgets=[8, 16, 32, 64])
    assert len(slots_prompts) == 4
    assert all(p.shape == (128,) for p in slots_prompts)

    # Golden prompt defaults
    assert isinstance(DEFAULT_GOLDEN_PROMPT, str)
    assert DEFAULT_GOLDEN_MAX_OUTPUT_TOKENS > 0


def test_variable_length_prompt_generation_smoke():
    """Verify that variable length prompts generated by prompt.py work end-to-end with generate()."""
    model = build_tiny_model()
    device = torch.device("cpu")
    vocab_size = model.config.vocab_size

    # Generate unequal length prompts (e.g. lengths 4 and 2)
    prompts = make_prompt(vocab_size, [4, 2], device=device)

    mode = Mode({FeatureFlag.KV_CACHE}, batching=BatchingMethod.FIXED)
    res = generate(
        mode=mode,
        model=model,
        input_ids=prompts,
        max_new_tokens=4,
        eos_token_id=-1,
        device=device,
        stop_on_eos=False,
    )
    assert res.padded_output_tokens().shape == (2, 4)
    assert len(res.sequences) == 2
    assert res.sequences[0].request_index == 0
    assert res.sequences[1].request_index == 1
    assert len(res.sequences[0].token_ids) == 4
    assert len(res.sequences[1].token_ids) == 4
