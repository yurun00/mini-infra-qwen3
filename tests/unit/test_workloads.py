def test_variable_length_prompt_generation_smoke():
    """Verify that variable length prompts generated by workloads.py work end-to-end with generate()."""
    model = build_tiny_model()
    device = torch.device("cpu")
    vocab_size = model.config.vocab_size

    # Generate unequal length prompts (e.g. lengths 4 and 2)
    prompts = make_prompt(vocab_size, [4, 2])

    mode = Mode(CachingMethod.DENSE, batching_method=BatchingMethod.FIXED)
    res = generate(
        mode=mode,
        model=model,
        prompts=prompts,
        max_new_tokens=4,
        options=GenerationOptions(eos_token_id=-1, device=device, stop_on_eos=False),
    )
    assert res.padded_output_tokens().shape == (2, 4)
    assert len(res.sequences) == 2
    assert res.sequences[0].request_idx == 0
    assert res.sequences[1].request_idx == 1
    assert len(res.sequences[0].token_ids) == 4
    assert len(res.sequences[1].token_ids) == 4


def test_make_arrival_times():
    import pytest

    assert make_arrival_times(4, 150.0) == [0.0, 150.0, 300.0, 450.0]
    assert make_arrival_times(1, 0.0) == [0.0]
    with pytest.raises(ValueError):
        make_arrival_times(0, 10.0)
    with pytest.raises(ValueError):
        make_arrival_times(3, -5.0)


def test_canonical_workloads_and_build_payload():
    from mini_infra.bench.spec.release import get_release_spec

    lockstep_workloads = release_workloads("lockstep")
    scheduler_workloads = release_workloads("scheduler")
    assert set(lockstep_workloads) == set(RELEASE_SCALES)
    assert set(scheduler_workloads) == set(RELEASE_SCALES)

    lockstep_spec = get_release_spec("lockstep")
    scheduler_spec = get_release_spec("scheduler")
    assert lockstep_spec.spec.execution.warmup >= 1
    assert scheduler_spec.spec.execution.warmup >= 1

    for scale in RELEASE_SCALES:
        lw = lockstep_workloads[scale]
        assert isinstance(lw, ResolvedWorkloadSpec)
        assert lw.workload_id == f"lockstep_{scale}"
        assert isinstance(lw.prompt_len, tuple) and len(lw.prompt_len) == lw.num_total_requests
        assert isinstance(lw.max_new_tokens, tuple) and len(lw.max_new_tokens) == lw.num_total_requests

        sw = scheduler_workloads[scale]
        assert isinstance(sw, ResolvedWorkloadSpec)
        assert sw.workload_id == f"scheduler_{scale}"
        assert isinstance(sw.prompt_len, tuple) and len(sw.prompt_len) == sw.num_total_requests
        assert isinstance(sw.max_new_tokens, tuple) and len(sw.max_new_tokens) == sw.num_total_requests
        assert isinstance(sw.arrival_ms, tuple) and len(sw.arrival_ms) == sw.num_total_requests

        payload = RequestPayload.from_spec(sw, vocab_size=32000)
        assert payload.request_count == sw.num_total_requests
        assert payload.prompt_lengths == sw.prompt_lens
        assert payload.output_budgets == sw.output_budgets
        assert payload.arrival_times_ms == sw.arrival_ms

    # Different seeds produce different pseudo-random configurations
    assert (
        release_workloads("lockstep", seed=42)["medium"].prompt_len
        != release_workloads("lockstep", seed=43)["medium"].prompt_len
    )
    assert (
        release_workloads("scheduler", seed=42)["medium"].arrival_ms
        != release_workloads("scheduler", seed=43)["medium"].arrival_ms
    )


def test_release_benchmark_script_dry_run(capsys):
    from mini_infra.cli.commands.bench import release

    # Test lockstep dry-run
    rc_lockstep = release.main(
        [
            "--engine",
            "lockstep",
            "--tag",
            "v0.3.0",
            "--release-feature",
            "fixed batching",
            "--dry-run",
        ]
    )
    assert rc_lockstep == 0
    out_lockstep = capsys.readouterr().out
    assert "[1/5] 开始执行: 运行 Lockstep 基准 [small]" in out_lockstep
    assert "[2/5] 开始执行: 运行 Lockstep 基准 [medium]" in out_lockstep
    assert "[3/5] 开始执行: 运行 Lockstep 基准 [large]" in out_lockstep
    assert out_lockstep.count("--profile-mode extra-profile") == 1
    assert "--scale small --seed 42 --profile-mode extra-profile" in out_lockstep
    assert "-> 目标产物: benchmarks/result-history/lockstep/<commit>_v0.3.0.json" in out_lockstep

    # Test scheduler dry-run
    rc_scheduler = release.main(
        [
            "--engine",
            "scheduler",
            "--tag",
            "v0.4.0",
            "--release-feature",
            "continuous batching",
            "--dry-run",
        ]
    )
    assert rc_scheduler == 0
    out_scheduler = capsys.readouterr().out
    assert "[1/5] 开始执行: 运行 Scheduler 基准 [small]" in out_scheduler
    assert "[2/5] 开始执行: 运行 Scheduler 基准 [medium]" in out_scheduler
    assert "[3/5] 开始执行: 运行 Scheduler 基准 [large]" in out_scheduler
    assert "-> 目标产物: benchmarks/result-history/scheduler/<commit>_v0.4.0.json" in out_scheduler
